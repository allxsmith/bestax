// Copy the canonical Agent Skills from the monorepo's top-level `skills/` into
// `bestax-mcp/data/skills`, so the server can serve their bodies offline from
// the published tarball.
//
// `/skills` is the single source of truth; `data/skills` is generated and
// gitignored. Runs on `build`, `test`, `test:coverage`, `test:watch` and
// `prepack`, and turbo runs the first three concurrently. That is why this
// caller passes a `stateDir`: scripts/lib/sync-skills.mjs, which does the copy
// for both packages, then takes a lock and skips a copy that is already
// current. See its "Concurrency" note for why both are needed.
//
// The MANIFEST (names, descriptions, reference lists) is committed instead, in
// data/skills.json — generated by scripts/gen-mcp-index.mjs. That is what the
// CI staleness gate watches, so a new or renamed skill still fails the build
// without a second committed copy of 390 KB of markdown bloating every diff.
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { failureText } from '../../scripts/lib/skills.mjs';
import { syncSkills } from '../../scripts/lib/sync-skills.mjs';

const pkgRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..'
);

await syncSkills({
  src: path.resolve(pkgRoot, '..', 'skills'),
  dest: path.join(pkgRoot, 'data', 'skills'),
  label: 'data/skills',
  // Lock and freshness stamp live in their own directory, NOT loose in
  // `data/`. `gen:mcp:check` runs `git add --intent-to-add --all
  // bestax-mcp/data` and diffs the result, so an untracked file anywhere else
  // under data/ would fail that gate. This path is gitignored alongside
  // data/skills itself, and `files` negates it so it never ships.
  stateDir: path.join(pkgRoot, 'data', '.sync-skills'),
}).catch(err => {
  console.error(failureText(err));
  process.exit(1);
});
