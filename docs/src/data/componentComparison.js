  name
    .split('.')[0] // "Button.Group" -> "Button"
    .replace(/\s*[+/].*$/, '') // "Button + input" -> "Button"
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/\s+/g, '-')
    .toLowerCase();

